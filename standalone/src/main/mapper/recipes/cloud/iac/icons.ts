export function awsIconKey(type: string): string {
	if (type.startsWith("AWS::")) {
		const [, service = "", resource = ""] = type.split("::");
		return CFN_AWS[`${service}::${resource}`] ?? CFN_AWS[service] ?? "general";
	}
	return TF_AWS.find(([p]) => type.startsWith(p))?.[1] ?? "general";
}

