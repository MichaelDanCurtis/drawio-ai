/** The style for a resource of a cloud. */
export function iacIconStyle(cloud: Cloud, type: string, kind?: string): { style: string; width: number; height: number } {
	if (cloud === "aws") return { style: awsIconStyle(awsIconKey(type)), width: 48, height: 48 };
	if (cloud === "azure") return { style: azureIconStyle(azureIconFile(type, kind)), width: 48, height: 48 };
	if (cloud === "gcp") return { style: gcpIconStyle(gcpIconName(type)), width: 56, height: 49 };
	return { style: "rounded=1;whiteSpace=wrap;html=1;fillColor=#f5f5f5;strokeColor=#999999;fontSize=11;", width: 150, height: 44 };
}
