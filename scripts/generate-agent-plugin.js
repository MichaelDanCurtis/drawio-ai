const check = process.argv.includes("--check");
let stale = 0;
for (const [rel, content] of Object.entries(files)) {
	const file = path.join(pluginDir, rel);
	const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : undefined;
	if (current === content) continue;
	if (check) {
		console.error(`agent-plugin/${rel} is out of date.`);
		stale++;
	} else {
		fs.mkdirSync(path.dirname(file), { recursive: true });
		fs.writeFileSync(file, content);
		console.log(`Wrote agent-plugin/${rel}`);
	}
}
for (const entry of pkg.contributes.chatSkills ?? []) {
	if (!fs.existsSync(path.join(root, entry.path))) {
		console.error(`package.json chatSkills names ${entry.path}, which does not exist.`);
		stale++;
	}
}
const skillNames = Object.keys(files).filter((f) => f.startsWith("skills/")).map((f) => `./agent-plugin/${f}`);
const contributed = (pkg.contributes.chatSkills ?? []).map((e) => e.path);
for (const s of skillNames) {
	if (!contributed.includes(s)) {
		console.error(`package.json chatSkills is missing ${s}.`);
		stale++;
	}
}
for (const bin of ["bin/draw-ai-mcp", "bin/draw-ai-mcp.cmd"]) {
	if (!fs.existsSync(path.join(pluginDir, bin))) {
		console.error(`agent-plugin/${bin} is missing.`);
		stale++;
	}
}
if (stale) {
	if (check) console.error("Run: node scripts/generate-agent-plugin.js");
	process.exit(1);
}
if (check) console.log("agent plugin in sync");
