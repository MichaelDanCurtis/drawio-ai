/** A section of the system prompt, from its heading to the next blank-line heading. */
function promptSection(heading) {
	const start = SYSTEM_PROMPT.indexOf(heading + "\n");
	if (start < 0) throw new Error(`systemPrompt.ts has no "${heading}" section`);
	const rest = SYSTEM_PROMPT.slice(start + heading.length + 1);
	const end = rest.search(/\n\n[A-Z][^\n]*:\n/);
	return (end < 0 ? rest : rest.slice(0, end)).trim();
}

